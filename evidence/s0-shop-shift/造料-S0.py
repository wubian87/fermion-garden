#!/usr/bin/env python3
"""239 造料-S0：把手写流 料-小说班-S0.json 搬成三臂同吃的跑班料。

⛔ 这不是生成器（要求-S0：流是手写的）——只做格式搬运＋标记行拼接＋sha 冻结：
  · 回复点＝52 点全量（工作点＝每条客户消息，234-B 同款）；班内 8 客户交错。
  · 标记行＝〔班第N点·会话Ck{·新客户}〕客户：<原文>（②③ feeder 逐点直贴；④ 记忆条目同文）。
  · 消息（④ 提示词字段用）＝〔班第N点·会话Ck{·新客户}〕<原文>（分诊/办理模板自带「客户：」前缀）。
  · 设定-S0.txt／店规-S0.txt 由同一份料生成（价目表只列真码；⛔ 近似码不进任何臂可见文本）。
产出：回复料-S0.json、设定-S0.txt、店规-S0.txt；打印各 sha（真跑-S0.sh 落断言）。
"""
import json, hashlib
from pathlib import Path

注地 = Path(__file__).resolve().parent
手写 = json.loads((注地 / "料-小说班-S0.json").read_text(encoding="utf-8"))
手写sha = hashlib.sha256((注地 / "料-小说班-S0.json").read_bytes()).hexdigest()

价目行 = []
for r in 手写["价目表"]:
    行 = f"- {r['sku']} {r['描述']}：常价 {r['常价']:.2f}"
    if r["活动价"] is not None:
        行 += f"；活动价 {r['活动价']:.2f}，到期点 {r['到期点']}"
    价目行.append(行)
口径行 = [f"- {c['问']}：{c['truth']}。" for c in 手写["口径表"]]
表块 = ("〔本店价目表〕「到期点」按班内点号对表：到班第 X 点及之后恢复常价、活动价失效；之前活动价有效。\n"
        + "\n".join(价目行) + "\n〔本店口径〕\n" + "\n".join(口径行))

设定 = """〔系统设定〕你是这家杯子铺的当班 AI 客服代理，独自连续接待一个接一个的客户（班内多名客户交错发言）。规则：
1. 每条「〔班第N点·会话Ck〕客户：…」是一位客户的消息：带「·新客户」的是 Ck 这位客户的第一句话，不带的是同一位客户的后续发言；每条都要以客服身份直接回复这位客户本人，不要把话回给别的客户。
2. 「班第N点」是班内时间戳，价目表活动价的「到期点」按它对表。
3. 回复要求：本店客服口吻（可称「亲」），只依据对话里已有的事实与本店价目表、口径答复；客户报的商品码在价目表里查不到时如实说查不到、并请客户核对，不要编造；不知道的不编造，不承诺没有依据的日期、金额与赔偿；必要时请客户稍等或补充信息。
4. 每条回复的最后一行固定写：【转人工】是 或 【转人工】否（判断这位客户当下该不该转人工客服处理）。
5. 直接以中文回复正文开头；不要输出思考过程、英文或任何前言。

""" + 表块

店规 = ("本店客服规范：只依据客户提供与系统可查的事实答复；不编造订单号、日期、金额与承诺；口吻礼貌（可称「亲」）；"
        "给不了确定答案时如实说需要核实、请客户稍等；客户情绪激烈或问题超出权限时建议转人工。"
        "客户报的商品码在价目表里查不到时如实说查不到、并请客户核对，不要编造。\n\n" + 表块)

陷类表 = {a["点"]: a["类"] for a in 手写["标准答案"]}
流, 点表 = [], []
seen = set()
for p in 手写["流"]:
    n, k, msg = p["点"], p["客户"], p["消息"]
    新客 = k not in seen
    seen.add(k)
    标 = f"〔班第{n}点·会话{k}{'·新客户' if 新客 else ''}〕"
    标记行 = f"{标}客户：{msg}"
    会话内序 = sum(1 for q in 点表 if q["会话"] == k)
    流.append({"会话": k, "序": 会话内序, "角色": "客户", "文本": 标记行, "点": n,
               "话题": p["话题"], "指代": p["指代"]})
    点表.append({"会话": k, "流序": n - 1, "班点": n, "会话内序": 会话内序,
                 "消息": f"{标}{msg}", "标记行": 标记行, "原文": msg,
                 "话题": p["话题"], "指代": p["指代"],
                 "判定": n in 陷类表, "陷类": 陷类表.get(n), "探针": False, "参照回复": None})

统计 = {"点数": len(点表), "客户数": len({p["会话"] for p in 点表}), "判定点数": sum(p["判定"] for p in 点表),
        "手写料sha256": 手写sha, "K": 手写["meta"]["K"],
        "相邻同客户": any(a["会话"] == b["会话"] for a, b in zip(点表, 点表[1:]))}
assert 统计["点数"] == 52 and 统计["客户数"] == 8 and not 统计["相邻同客户"]
料 = {"流": 流, "回复点": 点表, "统计": 统计,
      "料sha256": hashlib.sha256(json.dumps({"流": 流, "回复点": 点表}, ensure_ascii=False).encode()).hexdigest()}
(注地 / "回复料-S0.json").write_text(json.dumps(料, ensure_ascii=False, indent=1), encoding="utf-8")
(注地 / "设定-S0.txt").write_text(设定, encoding="utf-8")
(注地 / "店规-S0.txt").write_text(店规, encoding="utf-8")
print(json.dumps({"统计": 统计, "料sha256": 料["料sha256"],
                  "设定sha256": hashlib.sha256(设定.encode()).hexdigest()[:16],
                  "店规sha256": hashlib.sha256(店规.encode()).hexdigest()[:16]}, ensure_ascii=False))
